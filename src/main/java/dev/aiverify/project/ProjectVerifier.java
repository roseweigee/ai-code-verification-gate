package dev.aiverify.project;

import dev.aiverify.json.Json;
import dev.aiverify.pipeline.AuditLog;
import dev.aiverify.pipeline.Hashing;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.OffsetDateTime;
import java.time.temporal.ChronoUnit;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.concurrent.TimeUnit;
import java.util.stream.Stream;

/**
 * Verifies a whole project generated by SpecBlast (or any Spring Boot + Kubernetes generator):
 *
 *   P1 Java security policy   P2 CodingStyle.md contract   P3 Kubernetes manifests
 *   P4 delivery pipeline      P5 tests and code quality    P6 Maven build and tests (when Maven is available)
 *
 * Any ERROR blocks the deployment. WARN goes to the human approver. Exit code 1 when blocked, so CI stops.
 */
public final class ProjectVerifier {

    public record Gate(String id, String name, List<Finding> findings, String status, String note) {
        Map<String, Object> toMap() {
            Map<String, Object> m = new LinkedHashMap<>();
            m.put("id", id);
            m.put("name", name);
            m.put("status", status);
            m.put("note", note);
            m.put("errors", findings.stream().filter(f -> f.severity().equals("ERROR")).count());
            m.put("warnings", findings.stream().filter(f -> f.severity().equals("WARN")).count());
            m.put("passed", findings.stream().filter(f -> f.severity().equals("PASS")).count());
            List<Map<String, Object>> fs = new ArrayList<>();
            findings.forEach(f -> fs.add(f.toMap()));
            m.put("findings", fs);
            return m;
        }
    }

    public static Map<String, Object> verify(Path gateRoot, Path project, String label, boolean build) {
        Path root = project.toAbsolutePath().normalize();
        if (!Files.isDirectory(root)) {
            throw new IllegalArgumentException("Not a folder: " + root);
        }
        Map<Path, String> javaFiles = new TreeMap<>();
        Map<Path, String> yaml = new TreeMap<>();
        Map<Path, String> all = new TreeMap<>();
        String cloudbuild = null;
        String cloudbuildFile = null;
        try (Stream<Path> s = Files.walk(root)) {
            for (Path p : s.filter(Files::isRegularFile).toList()) {
                String rel = root.relativize(p).toString();
                boolean hidden = java.util.Arrays.stream(rel.split("/")).anyMatch(seg -> seg.startsWith("."));
                if (hidden || rel.startsWith("target/") || rel.contains("node_modules/")) {
                    continue;
                }
                String name = p.getFileName().toString();
                if (name.endsWith(".java")) {
                    javaFiles.put(p, read(p));
                    all.put(p, javaFiles.get(p));
                } else if (name.equals("cloudbuild.yaml") || name.equals("cloudbuild.yml")) {
                    cloudbuild = read(p);
                    cloudbuildFile = rel;
                    all.put(p, cloudbuild);
                } else if ((name.endsWith(".yaml") || name.endsWith(".yml")) && rel.startsWith("k8s/")) {
                    yaml.put(p, read(p));
                    all.put(p, yaml.get(p));
                } else if (name.equals("Dockerfile") || name.equals("CodingStyle.md") || name.equals("pom.xml")) {
                    all.put(p, read(p));
                }
            }
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
        String style = readIfExists(root.resolve("CodingStyle.md"));
        String dockerfile = readIfExists(root.resolve("Dockerfile"));

        List<Gate> gates = new ArrayList<>();
        gates.add(gate("P1", "Java security policy", JavaPolicyRules.check(javaFiles, root), null));
        gates.add(gate("P2", "CodingStyle.md contract", CodingStyleRules.check(style, javaFiles, root),
                style == null ? null : "SpecBlast gives CodingStyle.md to the model as instructions; here it is checked as rules."));
        gates.add(gate("P3", "Kubernetes manifests", KubernetesRules.check(yaml, root), null));
        gates.add(gate("P4", "Delivery pipeline", PipelineRules.check(cloudbuildFile, cloudbuild, dockerfile,
                KubernetesRules.sharedImages(yaml, root)), null));
        gates.add(gate("P5", "Tests and code quality",
                QualityRules.check(javaFiles, root, readIfExists(root.resolve("pom.xml")), cloudbuild),
                "Generated Mockito tests come from the same AI as the code, so they are checked, not trusted."));
        gates.add(build ? mavenBuild(root) : new Gate("P6", "Maven build and tests", List.of(), "SKIPPED",
                "Not run here. Use --build where Maven can download dependencies; in Cloud Build this gate runs right after mvn verify."));

        long errors = gates.stream().flatMap(g -> g.findings().stream()).filter(f -> f.severity().equals("ERROR")).count();
        long warns = gates.stream().flatMap(g -> g.findings().stream()).filter(f -> f.severity().equals("WARN")).count();
        String verdict = errors > 0 ? "BLOCKED" : "READY_FOR_HUMAN_APPROVAL";

        StringBuilder manifest = new StringBuilder();
        all.forEach((p, text) -> manifest.append(root.relativize(p)).append(' ').append(Hashing.sha256(text)).append('\n'));
        String at = OffsetDateTime.now().truncatedTo(ChronoUnit.SECONDS).toString();

        Map<String, Object> result = new LinkedHashMap<>();
        result.put("label", label == null ? root.getFileName().toString() : label);
        result.put("project", root.getFileName().toString());
        result.put("verifiedAt", at);
        result.put("gitCommit", gitCommit(root));
        result.put("filesChecked", Map.of("java", javaFiles.size(), "kubernetes", yaml.size(), "total", all.size()));
        result.put("contentSha256", Hashing.sha256(manifest.toString()));
        result.put("verdict", verdict);
        result.put("errors", errors);
        result.put("warnings", warns);
        List<Map<String, Object>> gm = new ArrayList<>();
        gates.forEach(g -> gm.add(g.toMap()));
        result.put("gates", gm);

        Map<String, Object> event = new LinkedHashMap<>();
        event.put("event", "PROJECT_VERIFIED");
        event.put("at", at);
        event.put("project", result.get("label"));
        event.put("gitCommit", result.get("gitCommit"));
        event.put("verdict", verdict);
        event.put("errors", errors);
        event.put("warnings", warns);
        event.put("contentSha256", result.get("contentSha256"));
        new AuditLog(gateRoot.resolve("runs/audit-log.jsonl")).append(event);
        return result;
    }

    private static Gate gate(String id, String name, List<Finding> findings, String note) {
        boolean error = findings.stream().anyMatch(f -> f.severity().equals("ERROR"));
        boolean warn = findings.stream().anyMatch(f -> f.severity().equals("WARN"));
        return new Gate(id, name, findings, error ? "FAILED" : warn ? "WARNING" : "PASSED", note);
    }

    private static Gate mavenBuild(Path root) {
        List<Finding> f = new ArrayList<>();
        try {
            Process p = new ProcessBuilder("mvn", "-q", "-B", "verify").directory(root.toFile()).redirectErrorStream(true).start();
            byte[] out = p.getInputStream().readAllBytes();
            boolean done = p.waitFor(20, TimeUnit.MINUTES);
            String tail = tail(new String(out, StandardCharsets.UTF_8), 15);
            if (done && p.exitValue() == 0) {
                f.add(Finding.pass("P6-01", "pom.xml", "mvn verify passed: the project compiles and its tests pass"));
            } else {
                f.add(new Finding("P6-01", "ERROR", "pom.xml", 0, "mvn verify failed", tail,
                        "Fix the compile or test failures before deployment."));
            }
        } catch (IOException e) {
            return new Gate("P6", "Maven build and tests", f, "SKIPPED", "Maven is not installed: " + e.getMessage());
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            return new Gate("P6", "Maven build and tests", f, "SKIPPED", "Interrupted");
        }
        return gate("P6", "Maven build and tests", f, null);
    }

    private static String gitCommit(Path root) {
        try {
            if (!Files.exists(root.resolve(".git"))) {
                return null; // only report a commit when the project is its own repository
            }
            Process p = new ProcessBuilder("git", "-C", root.toString(), "rev-parse", "--short", "HEAD")
                    .redirectErrorStream(true).start();
            String s = new String(p.getInputStream().readAllBytes(), StandardCharsets.UTF_8).strip();
            return p.waitFor() == 0 ? s : null;
        } catch (IOException | InterruptedException e) {
            return null;
        }
    }

    private static String tail(String s, int n) {
        String[] lines = s.split("\n");
        return String.join("\n", java.util.Arrays.copyOfRange(lines, Math.max(0, lines.length - n), lines.length));
    }

    private static String read(Path p) {
        try {
            return Files.readString(p);
        } catch (IOException e) {
            return "";
        }
    }

    private static String readIfExists(Path p) {
        return Files.exists(p) ? read(p) : null;
    }

    public static String toJson(Map<String, Object> result) {
        return Json.write(result);
    }

    private ProjectVerifier() {
    }
}
